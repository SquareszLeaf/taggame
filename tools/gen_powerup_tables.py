"""Scan data.json for the powerup events and write the SID tables used by scripts/mods.js.

Run from the repo root:  python3 tools/gen_powerup_tables.py
Re-run it whenever the powerup/clone events in data.json change (writes scripts/mods_tables.js).
"""
import json, re

src = open('scripts/c3runtime.js').read()
m = re.search(r'self\.C3_GetObjectRefTable = function\(\) \{\s*return \[(.*?)\];', src, re.S)
refs = [x.strip().split('.')[-1] for x in m.group(1).split(',') if x.strip()]
d = json.load(open('data.json'))['project']
objs = [o[0] for o in d[3]]
PLAYERS = {'p1', 'p2', 'p3', 'p4'}
# constant expressions used by the powerup actions (index -> value, from C3_ExpressionFuncs)
CONST = {165: 1200, 167: 600, 169: 1500, 159: 1800, 161: 1000, 170: 2000, 182: 200, 166: 7}
NORMAL = {'speed': 600, 'jump': 1000, 'gravity': 2000}
STAT = {'SetMaxSpeed': 'speed', 'SetJumpStrength': 'jump', 'SetGravity': 'gravity'}
BUFF_NAME = {'Speed - 1': 'speed', 'Jump- 2': 'jump', 'shield - 4': 'shield', 'super - 5': 'super',
             'fly- 6': 'fly', 'small - 8': 'small', 'big - 9': 'big', 'trampoline': 'trampoline'}
CATEGORY = {'small': 'size', 'big': 'size'}

stat_acts, waits = {}, {}

def player_of(ev):
    for c in ev[6]:
        if objs[c[0]] in PLAYERS and refs[c[1]] == 'OnCollision':
            return objs[c[0]]

def walk(evs, buff, player):
    for e in evs:
        if e[0] not in (0, 3):
            continue
        b = BUFF_NAME.get(e[1][1], buff) if e[0] == 3 else buff
        p = player_of(e) or player
        for a in e[7]:
            name = refs[a[1]]
            if not b:
                continue
            if name in STAT and objs[a[0]] in PLAYERS:
                expr = a[6][0][1][0]
                stat = STAT[name]
                val = CONST[expr]
                stat_acts[a[3]] = [b, stat, 'reset' if val == NORMAL[stat] else 'apply']
            elif name == 'Wait' and a[0] == -1 and a[6][0][1] == [166] and p and b != 'trampoline':
                waits[a[3]] = [p, b, CATEGORY.get(b, b)]
        if len(e) > 8 and isinstance(e[8], list):
            walk(e[8], b, p)

for es in d[6]:
    walk(es[1], None, None)

# clone powerup: the scripted jumps/waits inside the clone-spawning sub-events
clone_jumps, clone_waits = [], []

def collect_clone(evs, in_clone):
    for e in evs:
        if e[0] not in (0, 3):
            continue
        spawns = any(refs[a[1]] == 'CreateObject' and objs[a[6][0][1]] in PLAYERS for a in e[7])
        here = in_clone or (e[0] == 0 and spawns)
        if here:
            for a in e[7]:
                if refs[a[1]] == 'SimulateControl':
                    clone_jumps.append(a[3])
                elif refs[a[1]] == 'Wait' and a[0] == -1:
                    clone_waits.append(a[3])
        if len(e) > 8 and isinstance(e[8], list):
            collect_clone(e[8], here)

def find_group(evs, name):
    for e in evs:
        if e[0] == 3:
            if e[1][1] == name:
                return e
            g = find_group(e[8] if len(e) > 8 else [], name)
            if g:
                return g

for es in d[6]:
    g = find_group(es[1], 'trumpoline - 7')
    if g:
        collect_clone(g[8], False)

# SIDs stay numeric so they round exactly like the runtime's own JSON.parse of data.json
lines = [
    '// generated by tools/gen_powerup_tables.py - do not edit by hand',
    'self.TagModTables = {',
    '    STAT_ACTS: new Map(' + json.dumps([[k, v] for k, v in stat_acts.items()]) + '),',
    '    BUFF_WAITS: new Map(' + json.dumps([[k, v] for k, v in waits.items()]) + '),',
    '    CLONE_JUMPS: new Set(' + json.dumps(clone_jumps) + '),',
    '    CLONE_WAITS: new Set(' + json.dumps(clone_waits) + '),',
    '};',
]
open('scripts/mods_tables.js', 'w').write('\n'.join(lines) + '\n')
print('wrote scripts/mods_tables.js:', len(stat_acts), 'stat actions,', len(waits), 'buff waits,', len(clone_jumps), 'clone jumps')
